#Barcode Management Program
"""This program takes in input data (Name,Price and Date) and uses the hashlib module to convert the input data into hexadecimal version of a fixed size (3+3+3 bytes) and converts it into binary.
A barcode is generated by assigning 0's to "│"(Unicode Character : U+2502) and assigning 1's to "▌"(Unicode Character : U+258C).
█││  is the start code which lets the scanner know where to start and   █▌│█ is the end code which lets the scanner know where 
to end scanning.This Program does not use any traditional barcode algorithms. We will have to create our own scanner inorder to use this program in a practical environment"""
import hashlib
def Barcode_Generator(Name,Price,Date):
    Encoded_Name,Encoded_Price,Encoded_Date=bin(int((hashlib.blake2s(Name.encode('utf-8'),digest_size=3)).hexdigest(),16))[2:],bin(int((hashlib.blake2s(Price.encode('utf-8'),digest_size=3)).hexdigest(),16))[2:],bin(int((hashlib.blake2s(Date.encode('utf-8'),digest_size=3)).hexdigest(),16))[2:]
    #The digest size is 3 since 3 bytes results in 6 hexadecimal digits (1 byte = 2 hexadecimal digits) which on further convertion into binary results in 24 binary digits.'utf-8' is used for unicode character support
    Checksum=bin(((int(Encoded_Name,2)+int(Encoded_Date,2)+int(Encoded_Price,2)))%128)[2:]  #Checksum ensures a good amount of precision for scanning the barcode. Once the scanner scans the barcode, the scanner will recalculate the checksum from the data it has read. if the checksum does not match with the checksum it read, the match will fail
    Checksum=(7-len(Checksum))*"0"+Checksum #This is to ensure constant length of checksum value
    Barcode_Binary=f"{('0'*(24-len(Encoded_Name)))+Encoded_Name} {('0'*(24-len(Encoded_Price)))+Encoded_Price} {('0'*(24-len(Encoded_Date)))+Encoded_Date} {Checksum}"
    Barcode="█││  "+Barcode_Binary.replace("0","│").replace("1","▌")+"  █▌│█"# │ --> unicode character : U+2502      ▌ --> unicode character : U+258C
    """ █││  is the start code which lets the scanner know where to start and   █▌│█ is the end code which lets the scanner know where to end scanning
    the start code consists of ' █,│ and │ ' █ --> unicode character : U+2588  │ --> unicode character : U+2502
    the end code consists of ' █,▌,│ and █ ' █ --> unicode character : U+2588  ▌ --> unicode character : U+258C  │ --> unicode character : U+2502"""
    Barcode_Binary=Barcode_Binary.replace(" ","")
    Barcode_Decimal=int(Barcode_Binary,2)
    return (Barcode,Barcode_Binary,Barcode_Decimal)
