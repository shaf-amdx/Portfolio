def Validate_Price(Price):
    if Price=="":
        Message("ENTERED FIELD IS EMPTY, PLEASE ENTER A VALID INPUT!",":")
        return (False,"")
    try:
        message_printed=False
        if ("XX" in Price):
            raise Exception
        for j in Price:
            if j not in "1234567890.+-/*()%^X ":
                raise Exception
            if j=="^":
                Price=Price.replace("^","**")
            if j in "X":
                Price=Price.replace("X","*")
        Price=str(float(eval(Price)))
        #The eval function is used to make the price field have a calculator feature
        if float(Price)<0:
            Message("You cannot enter a negative value!",":")
            message_printed=True
            raise Exception
    except ZeroDivisionError:
        Message("YOU CANNOT DIVIDE BY ZERO!",":")
        return (False,"")
    except OverflowError:
        Message("THE NUMBER IS TOO LARGE!",":")
        return(False,"")
    except:
        if not message_printed:
            Message("INVALID INPUT!",":")
        return (False,"")
    else:
        return (True,Price)
